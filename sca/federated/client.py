"""Federated learning clients.

Clients ``i = 1, ..., n`` produce local updates ``Delta_{t,i}``.  Byzantine
clients ``B subset {1,...,n}`` may submit arbitrary ``Delta_{t,i}``.

THREAT MODEL (this is the fix for audit finding F6).
--------------------------------------------------
The previous version of this file generated Byzantine updates as fresh
zero-mean Gaussian noise::

    delta[name] = -torch.randn_like(param) * 0.01 * scale

That is not an attack.  It does not depend on the honest updates, on the
model, or on the task; two "coordinated" attackers had cosine similarity
around ``-0.007``; and in the shipped logs it *raised* FedAvg accuracy from
0.84 to 0.9225, because averaging in independent zero-mean noise is a mild
regulariser.

The rebuilt threat model is the standard **omniscient Byzantine** model used
by Xie et al. (2020) and Baruch et al. (2019): the adversary observes the
honest clients' updates for the current round before choosing its own.  The
server therefore collects honest updates first and only then asks the
Byzantine clients for theirs.  Concretely:

* :class:`BenignClient` runs local SGD and returns ``theta_local - theta_global``.
* :class:`ByzantineClient` wraps a :class:`~sca.experiments.attacks.ByzantineAttack`
  and **requires** ``benign_deltas``.  Calling it without them raises.

Two extra hooks exist because real attacks need them:

* ``honest_delta``   -- the update this attacker *would* have sent if honest.
  ``sign_flip`` negates exactly this, so the attack is a function of the
  attacker's real gradient rather than of fresh noise.
* ``poisoned_delta`` -- the update obtained by running the same local SGD on
  relabelled data.  The targeted safety-degradation attack uses this.
"""

from __future__ import annotations

import copy
from abc import ABC, abstractmethod
from dataclasses import dataclass
from typing import Any, Callable, Mapping, Sequence

import torch
import torch.nn as nn
from torch.utils.data import DataLoader

__all__ = [
    "ClientUpdate",
    "FLClient",
    "BenignClient",
    "ByzantineClient",
    "local_sgd",
    "flatten_delta",
    "delta_norm",
    "scale_delta",
    "MissingBenignDeltasError",
]


class MissingBenignDeltasError(ValueError):
    """Raised when a Byzantine client is asked for an update with no benign context.

    Existence of this error is the enforcement mechanism for the API rule
    "every attack takes ``benign_deltas`` as a REQUIRED argument".
    """


# ---------------------------------------------------------------------------
# Update container and tensor helpers
# ---------------------------------------------------------------------------


@dataclass
class ClientUpdate:
    """A client's local update ``Delta_{t,i}``.

    Attributes:
        client_id: Client identifier.
        delta: Parameter update, keyed exactly like ``model.named_parameters()``.
        n_samples: Number of local training samples used (0 for clients that
            do not train, e.g. pure model-poisoning attackers).
        is_byzantine: Ground-truth adversary flag.  Used ONLY for diagnostics
            and for post-hoc analysis; no aggregator is allowed to read it.
        metadata: Free-form auditing metadata.
    """

    client_id: int
    delta: dict[str, torch.Tensor]
    n_samples: int = 0
    is_byzantine: bool = False
    metadata: dict[str, Any] | None = None


def flatten_delta(
    delta: Mapping[str, torch.Tensor],
    keys: Sequence[str] | None = None,
) -> torch.Tensor:
    """Flatten a parameter dict into a single 1-D tensor in a fixed key order.

    Args:
        delta: Parameter dict.
        keys: Explicit key order.  Defaults to ``sorted(delta)`` so that two
            dicts with the same keys always flatten compatibly.
    """
    if keys is None:
        keys = sorted(delta)
    parts = [delta[k].reshape(-1).to(torch.float64) for k in keys]
    if not parts:
        return torch.zeros(0, dtype=torch.float64)
    return torch.cat(parts)


def delta_norm(delta: Mapping[str, torch.Tensor]) -> float:
    """L2 norm of the flattened update."""
    return float(flatten_delta(delta).norm().item())


def scale_delta(
    delta: Mapping[str, torch.Tensor], factor: float
) -> dict[str, torch.Tensor]:
    """Return a new dict with every tensor multiplied by ``factor``."""
    return {name: value * factor for name, value in delta.items()}


