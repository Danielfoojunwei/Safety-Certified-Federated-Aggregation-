"""``python -m sca.experiments.run_soundness`` -- hypothesis H1 / criterion C3.

The Monte-Carlo coverage experiment for Theorem 1 lives in
``tests/test_stats.py`` as a pass/fail assertion.  A paper cannot cite a
pass/fail: it needs the coverage *numbers*, the number of failing trials, and
the negative controls that prove the experiment has the power to detect an
invalid bound.  This module runs the same experiment and writes those numbers
to ``results/soundness_theorem1.json``, so criterion C6 (every headline number
is regenerated by a committed script) holds for H1 as well.

WHAT IS MEASURED
----------------
For each of ``trials`` independent trials and each of ``K`` regions we draw an
i.i.d. Bernoulli(p_j) stream of length ``M`` (the a-priori per-region budget
cap) and then let adversaries choose a data-dependent stopping time m_j:

  optimal_stopping     sees the whole sample path and picks, per region, the
                       m in [1, M] that MINIMISES the UCB.  No real allocator
                       can do better at breaking the bound, so its coverage
                       lower-bounds coverage under any allocation rule.
  adaptive_realloc     takes a pilot of ``pilot`` samples in every region,
                       ranks regions by pilot p_hat, gives the full budget to
                       the half whose observed rate looks LOWEST, then applies
                       optimal stopping inside whatever each region got.  This
                       is literally the Stage-A -> Stage-B protocol's
                       allocation rule with the adversary's thumb on it.
  aggregate            the weighted certified quantity sum_j w_j UCB_j against
                       the truth sum_j w_j p_j.

NEGATIVE CONTROLS (these MUST fail to cover; if they cover, the experiment is
vacuous and the positive result means nothing):

  legacy_fixed_m       the same width without the ln(M) anytime inflation --
                       the bound the pre-rebuild repo shipped (finding F3).
  data_derived_k       finding F10 exactly: report only the ``keep``
                       best-looking regions, let K in ln(2K/delta) shrink to
                       the number that survived, and drop the missing weight.

Runtime is a few seconds on CPU; the default 20,000 trials is 10x the mandated
minimum because it costs nothing.
"""

from __future__ import annotations

import argparse
import json
import math
from dataclasses import asdict, dataclass
from typing import Sequence

import numpy as np

from sca.utils.paths import results_dir

__all__ = ["SoundnessConfig", "run_soundness", "main"]


@dataclass(frozen=True)
class SoundnessConfig:
    """A-priori constants.  ``k`` and ``budget_cap`` are declared here, not
    derived from any draw (finding F10)."""

    k: int = 12
    budget_cap: int = 4000
    delta: float = 0.10
    trials: int = 20000
    pilot: int = 32
    keep: int = 3
    p_true: float = 0.5  # maximal-variance regime -- the hardest case
    rng_seed: int = 20240729
    chunk: int = 2000


def _width_table(m_max: int, k_for_log: int, budget_for_log: int | None,
                 delta: float) -> np.ndarray:
    """Hoeffding half-width for m = 1..m_max.

    ``budget_for_log=None`` reproduces the OLD non-anytime width
    ``sqrt(ln(2k/delta) / (2m))`` used by the pre-rebuild repo.
    """
    ms = np.arange(1, m_max + 1, dtype=np.float64)
    if budget_for_log is None:
        c = math.log(2.0 * k_for_log / delta)
    else:
        c = math.log(2.0 * k_for_log * budget_for_log / delta)
    return np.sqrt(c / (2.0 * ms)).astype(np.float32)


def run_soundness(cfg: SoundnessConfig = SoundnessConfig()) -> dict:
    """Run the coverage experiment and return the results payload."""
    K, M, delta, T = cfg.k, cfg.budget_cap, cfg.delta, cfg.trials
    p_true = np.full(K, float(cfg.p_true))
    weights = np.full(K, 1.0 / K)
    rng = np.random.default_rng(cfg.rng_seed)

    ms = np.arange(1, M + 1, dtype=np.float32)
    w_new = _width_table(M, K, M, delta)          # Theorem 1 (anytime)
    w_old = _width_table(M, K, None, delta)       # negative control 1
    w_old_drop = _width_table(M, cfg.keep, None, delta)  # negative control 2

    log_term = math.log(2.0 * K * M / delta)
    eb_rem = np.full(M, np.inf, dtype=np.float64)
    eb_rem[1:] = 7.0 * log_term / (3.0 * (ms[1:].astype(np.float64) - 1.0))
    eb_rem = eb_rem.astype(np.float32)

    names = ("new_stop", "new_pilot", "old_stop", "old_drop_stop", "eb_stop",
             "pilot_phat")
    acc = {n: np.empty((T, K), np.float32) for n in names}

    # Chunk over trials so the (chunk, M) float32 buffer stays small.
    for j in range(K):
        for lo in range(0, T, cfg.chunk):
            hi = min(lo + cfg.chunk, T)
            x = rng.random((hi - lo, M), dtype=np.float32) < p_true[j]
            p_hat = np.cumsum(x, axis=1, dtype=np.float32) / ms[None, :]

            acc["new_stop"][lo:hi, j] = np.minimum(
                1.0, p_hat + w_new[None, :]).min(axis=1)
            acc["old_stop"][lo:hi, j] = np.minimum(
                1.0, p_hat + w_old[None, :]).min(axis=1)
            acc["old_drop_stop"][lo:hi, j] = np.minimum(
                1.0, p_hat + w_old_drop[None, :]).min(axis=1)

            var = np.zeros_like(p_hat)
            var[:, 1:] = (ms[1:] / (ms[1:] - 1.0))[None, :] * p_hat[:, 1:] * (
                1.0 - p_hat[:, 1:])
            eb_w = np.sqrt(2.0 * var * log_term / ms[None, :]) + eb_rem[None, :]
            acc["eb_stop"][lo:hi, j] = np.minimum(1.0, p_hat + eb_w).min(axis=1)

            acc["pilot_phat"][lo:hi, j] = p_hat[:, cfg.pilot - 1]
            acc["new_pilot"][lo:hi, j] = np.minimum(
                1.0, p_hat[:, :cfg.pilot] + w_new[None, :cfg.pilot]).min(axis=1)
            del x, p_hat, var, eb_w

    def simultaneous(ucb: np.ndarray) -> tuple[float, int]:
        failed = (p_true[None, :] > ucb + 1e-6).any(axis=1)
        return 1.0 - float(failed.mean()), int(failed.sum())

    # Adversary 2: pilot -> reallocate to the lowest-looking half.
    order = np.argsort(acc["pilot_phat"], axis=1)
    half = K // 2
    give_full = np.zeros((T, K), dtype=bool)
    rows = np.repeat(np.arange(T), half)
    give_full[rows, order[:, :half].ravel()] = True
    realloc = np.where(give_full, acc["new_stop"], acc["new_pilot"])

    true_agg = float((weights * p_true).sum())

    def aggregate(ucb: np.ndarray) -> tuple[float, int]:
        bound = (weights[None, :] * ucb).sum(axis=1)
        failed = true_agg > bound + 1e-6
        return 1.0 - float(failed.mean()), int(failed.sum())

    cov_stop, f_stop = simultaneous(acc["new_stop"])
    cov_realloc, f_realloc = simultaneous(realloc)
    cov_agg, f_agg = aggregate(acc["new_stop"])
    cov_eb, f_eb = simultaneous(acc["eb_stop"])
    cov_old, f_old = simultaneous(acc["old_stop"])

    # Negative control 2: keep only the `keep` best-looking regions and let K
    # in the log shrink to that number, dropping the missing weight entirely.
    order2 = np.argsort(acc["old_drop_stop"], axis=1)[:, : cfg.keep]
    kept_ucb = np.take_along_axis(acc["old_drop_stop"], order2, axis=1)
    kept_w = np.take_along_axis(np.tile(weights, (T, 1)), order2, axis=1)
    bound_drop = (kept_w * kept_ucb).sum(axis=1)
    cov_drop = float((true_agg <= bound_drop + 1e-6).mean())

    target = 1.0 - delta
    mean_bound_new = float((weights[None, :] * acc["new_stop"]).sum(axis=1).mean())
    mean_bound_old = float((weights[None, :] * acc["old_stop"]).sum(axis=1).mean())

    return {
        "config": asdict(cfg),
        "target_coverage_1_minus_delta": target,
        "true_weighted_violation_rate": true_agg,
        "H1_coverage": {
            "optimal_stopping_adversary": {
                "coverage": cov_stop, "n_failed_trials": f_stop,
                "n_trials": T, "passes": bool(cov_stop >= target)},
            "adaptive_reallocation_adversary": {
                "coverage": cov_realloc, "n_failed_trials": f_realloc,
                "n_trials": T, "passes": bool(cov_realloc >= target)},
            "weighted_aggregate": {
                "coverage": cov_agg, "n_failed_trials": f_agg,
                "n_trials": T, "passes": bool(cov_agg >= target)},
            "empirical_bernstein_optional_variant": {
                "coverage": cov_eb, "n_failed_trials": f_eb,
                "n_trials": T, "passes": bool(cov_eb >= target)},
        },
        "negative_controls": {
            "legacy_fixed_m_width": {
                "coverage": cov_old, "n_failed_trials": f_old,
                "must_fail_to_cover": True,
                "correctly_fails": bool(cov_old < target),
                "note": ("the pre-rebuild width sqrt(ln(2K/delta)/(2m)); if this "
                         "covered, the positive result would be vacuous"),
            },
            "data_derived_k_dropping_empty_regions": {
                "coverage": cov_drop,
                "must_fail_to_cover": True,
                "correctly_fails": bool(cov_drop < target),
                "note": "finding F10 reproduced exactly",
            },
        },
        "cost_of_the_anytime_correction": {
            "mean_certified_bound_theorem1": mean_bound_new,
            "mean_certified_bound_legacy": mean_bound_old,
            "inflation": mean_bound_new - mean_bound_old,
            "note": ("the price of soundness under adaptive allocation: the "
                     "ln(M) factor widens every interval by this much on "
                     "average, at p=0.5 and m chosen adversarially"),
        },
    }


def main(argv: Sequence[str] | None = None) -> int:
    ap = argparse.ArgumentParser(
        prog="python -m sca.experiments.run_soundness", description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--trials", type=int, default=SoundnessConfig.trials)
    ap.add_argument("--k", type=int, default=SoundnessConfig.k)
    ap.add_argument("--budget-cap", type=int, default=SoundnessConfig.budget_cap)
    ap.add_argument("--delta", type=float, default=SoundnessConfig.delta)
    ap.add_argument("--out", default="soundness_theorem1.json")
    args = ap.parse_args(argv)

    cfg = SoundnessConfig(k=args.k, budget_cap=args.budget_cap,
                          delta=args.delta, trials=args.trials)
    payload = run_soundness(cfg)
    path = results_dir() / args.out
    path.write_text(json.dumps(payload, indent=2))

    h1 = payload["H1_coverage"]
    nc = payload["negative_controls"]
    tgt = payload["target_coverage_1_minus_delta"]
    print(f"Theorem 1 Monte Carlo: K={cfg.k} M={cfg.budget_cap} "
          f"delta={cfg.delta} trials={cfg.trials} p_true={cfg.p_true}")
    print(f"  target coverage >= {tgt:.4f}")
    for name, row in h1.items():
        print(f"  {name:42s} {row['coverage']:.4f} "
              f"({row['n_failed_trials']}/{row['n_trials']} failed)  "
              f"{'PASS' if row['passes'] else 'FAIL'}")
    print("  negative controls (must NOT cover):")
    for name, row in nc.items():
        print(f"  {name:42s} {row['coverage']:.4f}  "
              f"{'correctly fails' if row['correctly_fails'] else 'DID NOT FAIL'}")
    print(f"  wrote {args.out}")
    return 0


if __name__ == "__main__":  # pragma: no cover - CLI
    raise SystemExit(main())
